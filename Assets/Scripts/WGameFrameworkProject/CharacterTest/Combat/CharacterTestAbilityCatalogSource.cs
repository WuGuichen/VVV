    public static class CharacterTestAbilityCatalogSource
    {
        public const string DefaultGeneratedCatalogPath =
            "Assets/MxFrameworkGenerated/Abilities/ability_catalog.json";

        public static AbilityRuntimeModule CreateRuntimeModule()
        {
            return new AbilityRuntimeModule(CreateRegistry(), "CharacterTest.AbilityRuntime");
        }

        public static AbilityDefinitionRegistry CreateRegistry()
        {
            AbilityDefinitionRegistry registry = LoadGeneratedOrEmpty(DefaultGeneratedCatalogPath);
            return registry.Count > 0 ? registry : CreateEmbeddedFallback();
        }

        public static AbilityDefinitionRegistry LoadGeneratedOrEmpty(string path)
        {
            return CharacterTestRuntimeCatalogBinaryFallback.LoadBinaryThenJsonOrEmpty(
                path,
                AbilityDefinitionBinaryImporter.CatalogKind,
                AbilityDefinitionBinaryImporter.ImportFile,
                AbilityDefinitionJsonImporter.ImportFile,
                registry => registry?.Count ?? 0,
                () => new AbilityDefinitionRegistry());
        }

