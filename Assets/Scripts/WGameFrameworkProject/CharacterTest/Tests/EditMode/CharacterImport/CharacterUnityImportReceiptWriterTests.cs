        [Test]
        public void TryValidate_RejectsIncompleteUnityAcceptance()
        {
            CreateEvidenceFiles();
            CharacterUnityImportExpectedIdentity expected = CreateExpected();

            CharacterImportedPackagePrefabBuildResult result = CreateReadyResult();
            result.CharacterActionActionSetReady = false;
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));

            result = CreateReadyResult();
            result.WeaponTraceBakeReady = false;
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));

            result = CreateReadyResult();
            result.SocketBakeReady = false;
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));

            result = CreateReadyResult();
            result.AbstractBoneStatus = "Failed";
            result.AbstractBoneResolvedCount = 1;
            result.AbstractBoneIssueCount = 1;
            result.AbstractBoneIssues = new[] { "head unresolved" };
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));

            result = CreateReadyResult();
            result.Issues = new[] { "spawn gate failed" };
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));

            result = CreateReadyResult();
            File.Delete(ToFullPath(result.RuntimePrefabPath));
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));

            result = CreateReadyResult();
            result.PrefabPath = "/Assets/MxFrameworkGenerated/CharacterPackages/"
                + PackageId
                + "/prefabs/authoring.prefab";
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidate(expected, result, out _));
        }

        [Test]
        public void EditorStatusPayload_PreservesRequestedIdentity_WhenBuildIdentityDiffers()
        {
            var request = new CharacterPackageImportRequestBridge.CharacterImportRebuildRequest
            {
                RequestId = "request-identity",
                Package = "Tools/MxFramework.Authoring/samples/character-requested",
                PackageId = "character-requested",
                SourcePackageHash = "sha256:requested-source",
                GeneratedConfigHash = "sha256:requested-config",
                GeometryBindingHash = "sha256:requested-geometry",
                ResourceMappingHash = "sha256:requested-resources",
                WritePlanHash = "sha256:requested-plan"
            };
            var result = new CharacterImportedPackagePrefabBuildResult
            {
                PackageId = "character-actual",
                SourcePackageHash = "sha256:actual-source",
                GeneratedConfigHash = "sha256:actual-config",
                GeometryBindingHash = "sha256:actual-geometry",
                ResourceMappingHash = "sha256:actual-resources",
                WritePlanHash = "sha256:actual-plan",
                ArtifactHash = "sha256:actual-artifact"
            };

            CharacterPackageImportRequestBridge.CharacterImportRebuildStatusFile status =
                CharacterPackageImportRequestBridge.BuildStatusPayload(
                    request,
                    "failed",
                    "identity mismatch",
                    string.Empty,
                    result);

            Assert.AreEqual("character-requested", status.PackageId);
            Assert.AreEqual("sha256:requested-source", status.SourcePackageHash);
            Assert.AreEqual("sha256:requested-config", status.GeneratedConfigHash);
            Assert.AreEqual("sha256:requested-geometry", status.GeometryBindingHash);
            Assert.AreEqual("sha256:requested-resources", status.ResourceMappingHash);
            Assert.AreEqual("sha256:requested-plan", status.WritePlanHash);
            Assert.AreEqual("sha256:actual-artifact", status.ArtifactHash);
        }

