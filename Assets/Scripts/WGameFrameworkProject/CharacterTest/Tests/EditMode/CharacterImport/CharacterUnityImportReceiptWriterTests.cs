        [Test]
        public void TryValidateAndWrite_WritesDeterministicTrackedReceipt()
        {
            CreateEvidenceFiles();
            CharacterUnityImportExpectedIdentity expected = CreateExpected();
            CharacterImportedPackagePrefabBuildResult result = CreateReadyResult();

            Assert.IsTrue(CharacterUnityEditorImportReceipt.TryValidateAndWrite(
                expected, result, out string assetPath, out string error), error);
            Assert.AreEqual(ReceiptPath, assetPath);
            string first = File.ReadAllText(ToFullPath(assetPath));

            result.DefaultWeaponResourceIds = new[] { "weapon.resource.sword", "weapon.resource.shield" };
            Assert.IsTrue(CharacterUnityEditorImportReceipt.TryValidateAndWrite(
                expected, result, out _, out error), error);
            string second = File.ReadAllText(ToFullPath(assetPath));

            Assert.AreEqual(first, second);
            Assert.IsTrue(File.Exists(ToFullPath(assetPath + ".meta")), "receipt meta should be generated by AssetDatabase import.");
            JObject json = JObject.Parse(first);
            Assert.AreEqual(CharacterUnityEditorImportReceipt.Format, (string)json["format"]);
            Assert.AreEqual(CharacterUnityEditorImportReceipt.SchemaVersion, (string)json["schemaVersion"]);
            Assert.IsTrue((bool)json["ready"]);
            Assert.AreEqual("sha256:generated", (string)json["hashes"]?["generatedConfigHash"]);
            Assert.AreEqual("sha256:palette-catalog", (string)json["material"]?["paletteCatalogHash"]);
            Assert.AreEqual(65536, (int)json["material"]?["paletteColorCount"]);
            Assert.AreEqual(16, (int)json["material"]?["surfaceProfileCount"]);
            Assert.AreEqual(0, (int)json["material"]?["invalidFaceCount"]);
            Assert.IsNull(json["material"]?["paletteProfileRow"]);
            CollectionAssert.AreEqual(
                new[] { "weapon.resource.shield", "weapon.resource.sword" },
                json["defaultWeaponResourceIds"]?.ToObject<string[]>());
            StringAssert.DoesNotContain("requestId", first);
            StringAssert.DoesNotContain("updatedUtc", first);
            StringAssert.DoesNotContain("message", first.ToLowerInvariant());
            StringAssert.DoesNotContain(Path.GetFullPath(Path.Combine(Application.dataPath, "..")), first);
        }

        [TestCase(false)]
        [TestCase(true)]
        public void TryValidateAndWrite_RejectsChangedSocketPairWithoutReplacingReceipt(bool changeIndex)
        {
            CreateEvidenceFiles();
            CharacterUnityImportExpectedIdentity expected = CreateExpected();
            CharacterImportedPackagePrefabBuildResult result = CreateReadyResult();
            Assert.IsTrue(CharacterUnityEditorImportReceipt.TryValidateAndWrite(expected, result, out _, out string error), error);
            string originalReceipt = File.ReadAllText(ToFullPath(ReceiptPath));
            if (changeIndex)
            {
                File.AppendAllText(ToFullPath(Root + "/" + CharacterSocketBakeCatalogBinary.DefaultIndexRelativePath), " ");
            }
            else
            {
                string path = ToFullPath(Root + "/" + CharacterSocketBakeCatalogBinary.DefaultBinaryRelativePath);
                byte[] bytes = File.ReadAllBytes(path);
                bytes[bytes.Length - 1] ^= 1;
                File.WriteAllBytes(path, bytes);
            }
            Assert.IsFalse(CharacterUnityEditorImportReceipt.TryValidateAndWrite(expected, result, out _, out error));
            StringAssert.Contains("Socket Bake", error);
            Assert.AreEqual(originalReceipt, File.ReadAllText(ToFullPath(ReceiptPath)));
        }

