            Assert.AreEqual("character.body.normal", (string)json["materials"]?[0]?["normalTextureResourceKey"]);
            Assert.AreEqual("character.body.mask", (string)json["materials"]?[0]?["maskTextureResourceKey"]);
            Assert.AreEqual("AlphaClip", (string)json["materials"]?[0]?["surfaceMode"]);
            Assert.AreEqual(0.42f, (float)json["materials"]?[0]?["alphaCutoff"], 0.0001f);
            Assert.AreEqual("AlphaClip", (string)json["material"]?["surfaceMode"]);
            Assert.AreEqual(0.42f, (float)json["material"]?["alphaCutoff"], 0.0001f);
            Assert.AreEqual("Eye", (string)json["materials"]?[1]?["sourceMaterialName"]);
            Assert.AreEqual("Ready", (string)json["socketBake"]?["status"]);
            Assert.AreEqual(result.SocketBakeRequestCount, (int)json["socketBake"]?["requestCount"]);
            Assert.AreEqual(result.SocketBakeSocketTrackCount, (int)json["socketBake"]?["socketTrackCount"]);
            Assert.AreEqual("Ready", (string)json["abstractBones"]?["status"]);
            CollectionAssert.AreEqual(new[] { "head" }, json["abstractBones"]?["requiredIds"]?.ToObject<string[]>());
            Assert.AreEqual(2, (int)json["abstractBones"]?["declaredCount"]);
            Assert.AreEqual(2, (int)json["abstractBones"]?["resolvedCount"]);
        }

