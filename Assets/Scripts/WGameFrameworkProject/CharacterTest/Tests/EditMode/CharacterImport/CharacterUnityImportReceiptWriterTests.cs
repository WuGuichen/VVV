        private static void CreateEvidenceFiles()
        {
            WriteEvidenceFile(Root + "/prefabs/authoring.prefab");
            WriteEvidenceFile(Root + "/runtime_resources/runtime.prefab");
            WriteEvidenceFile(Root + "/resources/character.fbx");
            WriteEvidenceFile(Root + "/materials/body.mat");
            WriteEvidenceFile(Root + "/materials/eye.mat");
            WriteEvidenceFile(Root + "/actions/profile.json");
            WriteEvidenceFile(Root + "/actions/action_sets.json");
            var catalog = new CharacterSocketBakeCatalog();
            byte[] binary = CharacterSocketBakeCatalogBinary.Serialize(PackageId, catalog);
            string indexPath = ToFullPath(Root + "/" + CharacterSocketBakeCatalogBinary.DefaultIndexRelativePath);
            Directory.CreateDirectory(Path.GetDirectoryName(indexPath));
            File.WriteAllText(indexPath, CharacterSocketBakeCatalogBinary.SerializeIndex(PackageId, catalog, binary));
            File.WriteAllBytes(ToFullPath(Root + "/" + CharacterSocketBakeCatalogBinary.DefaultBinaryRelativePath), binary);
        }

        private static void WriteEvidenceFile(string assetPath)
        {
            string fullPath = ToFullPath(assetPath);
            Directory.CreateDirectory(Path.GetDirectoryName(fullPath)!);
            File.WriteAllText(fullPath, "test");
        }

        private static string ToFullPath(string assetPath)
        {
            string projectRoot = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
            return Path.GetFullPath(Path.Combine(projectRoot, assetPath.Replace('/', Path.DirectorySeparatorChar)));
        }
