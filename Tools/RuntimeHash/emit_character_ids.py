"""Emit numeric runtime constants from the committed authoring identity catalog."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import definition_ids

def emit(catalog: Path, output: Path) -> None:
    document = json.loads(catalog.read_text(encoding='utf-8-sig'))
    definition_ids.validate(document)
    digest = bytes.fromhex(document['catalogHash'][7:])
    words = [int.from_bytes(digest[i:i+8], 'little') for i in range(0,32,8)]
    lines = ['// Generated by Tools/RuntimeHash/emit_character_ids.py. Do not renumber.',
             'using MxFramework.Runtime;', '', 'namespace MxFramework.Game.CharacterTest', '{',
             '    internal static class CharacterTestAuthoredContentIds', '    {',
             '        internal const string CatalogHash = '+json.dumps(document['catalogHash'])+';',
             '        internal const long Revision = '+str(document['revision'])+'L;']
    for domain in document['domains']:
        for entry in domain['entries']:
            # Retired constants remain visible so deleted numbers cannot silently be reused.
            lines.append('        internal const int D'+str(domain['domainId'])+'_Id'+str(entry['id'])+
                         ' = '+str(entry['id'])+'; // '+entry['status']+' '+entry['sourceKey'].replace('\n',' ').replace('\r',' '))
    # Preserve the legacy ordinal event precedence while comparing only integers during Tick.
    # UTF-16BE bytes reproduce StringComparer.Ordinal, including supplementary code units.
    lines += ['', '        internal static int GetEventOrder(int eventId) => GetLegacyOrdinalRank(401, eventId);',
              '        internal static int GetLegacyOrdinalRank(int domainId, int id)', '        {',
              '            if (id == 0) return 0;', '            switch (domainId)', '            {']
    for domain in document['domains']:
        ordered = sorted(domain['entries'], key=lambda e:e['sourceKey'].encode('utf-16-be', errors='surrogatepass'))
        lines += ['                case '+str(domain['domainId'])+':', '                    switch (id)', '                    {']
        for rank,entry in enumerate(ordered, 1):
            if entry['status'] == 'active':
                lines.append('                        case '+str(entry['id'])+': return '+str(rank)+';')
        lines += ['                    }', '                    break;']
    lines += ['            }', '            throw new System.ArgumentOutOfRangeException(nameof(id), "Unknown or retired definition identity.");', '        }']
    # Preserve the old anatomical category predicates at authoring time. Runtime
    # hit classification reads these fixed integer flags, never definition names.
    lines += ['', '        internal static int GetLegacyAnatomicalFlags(int id)', '        {', '            switch (id)', '            {']
    pose = next(domain for domain in document['domains'] if domain['domainId'] == 400)
    for entry in pose['entries']:
        if entry['status'] != 'active': continue
        text = entry['sourceKey'].lower()
        flags = (1 if 'high' in text else 0) | (2 if 'low' in text else 0) | (4 if 'mid' in text else 0)
        flags |= 8 if any(word in text for word in ('head', 'neck')) else 0
        flags |= 16 if any(word in text for word in ('leg', 'foot', 'knee', 'ankle')) else 0
        if flags: lines.append('                case '+str(entry['id'])+': return '+str(flags)+';')
    lines += ['                default: return 0;', '            }', '        }']
    lines += ['', '        internal static readonly RuntimeDefinitionIdCatalog Catalog = new RuntimeDefinitionIdCatalog(',
              '            Revision, new RuntimeHashDigest('+', '.join('0x%016xUL'%w for w in words)+'),',
              '            new RuntimeDefinitionIdEntry[]', '            {']
    for domain in document['domains']:
        for entry in domain['entries']:
            lines.append('                new RuntimeDefinitionIdEntry(new RuntimeDefinitionId('+str(domain['domainId'])+', '+str(entry['id'])+'), '+str(entry['status']=='retired').lower()+'),')
    lines += ['            });', '',
              '        internal static bool IsActive(int domainId, int value) => value > 0 && Catalog.IsActive(new RuntimeDefinitionId(domainId, value));',
              '    }', '}', '']
    output.parent.mkdir(parents=True,exist_ok=True)
    text='\n'.join(lines)
    if not output.exists() or output.read_text(encoding='utf-8-sig') != text:
        output.write_text(text,encoding='utf-8',newline='\n')

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('catalog',type=Path)
    parser.add_argument('output',type=Path)
    args=parser.parse_args()
    emit(args.catalog,args.output)
